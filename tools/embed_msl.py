#!/usr/bin/env python3
"""tools/embed_msl.py - writes shaders/metal.msl into src/gpu_msl.h as a C string, for the GPU renderer on
macOS (our Metal device, gx_metal.m, compiles the source when the game starts, so no shader compiler is needed
to build).
Original code for this project. Re-run after editing shaders/metal.msl:

  tools/embed_msl.py
"""
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = open(os.path.join(ROOT, 'shaders', 'metal.msl'), encoding='utf-8').read()
out = ['/* gpu_msl.h - generated by tools/embed_msl.py from shaders/metal.msl; do not edit. */',
       '#ifndef TL_GPU_MSL_H', '#define TL_GPU_MSL_H', '', 'static const char gpu_msl[] =']
for line in src.splitlines():
    out.append('  "' + line.replace('\\', '\\\\').replace('"', '\\"') + '\\n"')
out[-1] += ';'
out += ['', '#endif', '']
open(os.path.join(ROOT, 'src', 'gpu_msl.h'), 'w', encoding='utf-8').write('\n'.join(out))
