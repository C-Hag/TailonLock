#!/bin/sh
# Compiles shaders/*.hlsl into SPIR-V (Vulkan) and DXIL (Direct3D 12) with
# Microsoft's dxc and writes src/gpu_shaders.h, which is checked in, so a
# normal build needs no shader compiler. Re-run after editing a shader:
#
#   tools/build_shaders.sh
#
# dxc is downloaded once (pinned release) into build/_tools/dxc.
set -eu
ROOT=$(cd "$(dirname "$0")/.." && pwd)
TOOLS="$ROOT/build/_tools"
DXC="$TOOLS/dxc/bin/dxc"
URL=https://github.com/microsoft/DirectXShaderCompiler/releases/download/v1.9.2609/linux_dxc_2026_09_28.x86_x64.tar.gz
SHA=96faadc7f5c282d2ffda49804beb4c3ee38127bc252b723234e3c5cdf7aa39a1
if [ ! -x "$DXC" ]; then
  mkdir -p "$TOOLS/dxc"
  curl -sSL -o "$TOOLS/dxc.tgz" "$URL"
  echo "$SHA  $TOOLS/dxc.tgz" | sha256sum -c -
  tar -xzf "$TOOLS/dxc.tgz" -C "$TOOLS/dxc"
fi
export LD_LIBRARY_PATH="$TOOLS/dxc/lib${LD_LIBRARY_PATH:+:$LD_LIBRARY_PATH}"
OUT="$ROOT/src/gpu_shaders.h"
TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT

# name file entry stage
LIST="world_vs world vs_main vs
world_fs world fs_main ps
shadow_vs world vs_shadow vs
shadow_fs world fs_shadow ps
sky_vs sky vs_main vs
sky_fs sky fs_main ps
sprite_vs sprite vs_main vs
sprite_fs sprite fs_main ps
line_vs line vs_main vs
line_fs line fs_main ps
post_vs post vs_main vs
bright_fs post fs_bright ps
blur_fs post fs_blur ps
final_fs post fs_final ps"

{
  echo "/* gpu_shaders.h - generated by tools/build_shaders.sh from the HLSL in shaders/; do not edit. */"
  echo "#ifndef TL_GPU_SHADERS_H"
  echo "#define TL_GPU_SHADERS_H"
  echo "#include <stddef.h>"
  echo "#include <stdint.h>"
} > "$TMP/h"
echo "$LIST" | while read -r name file entry stage; do
  "$DXC" -nologo -O3 -T "${stage}_6_0" -E "$entry" -spirv -fspv-target-env=vulkan1.0 -fspv-entrypoint-name=main \
    -Fo "$TMP/$name.spv" "$ROOT/shaders/$file.hlsl"
  "$DXC" -nologo -O3 -Wno-ignored-attributes -T "${stage}_6_0" -E "$entry" -Fo "$TMP/$name.dxil" "$ROOT/shaders/$file.hlsl"
  for ext in spv dxil; do
    python3 - "$TMP/$name.$ext" "${name}_$ext" >> "$TMP/h" <<'PY'
import sys
data = open(sys.argv[1], 'rb').read()
print('static const uint8_t %s[%d] = {' % (sys.argv[2], len(data)))
for i in range(0, len(data), 24):
    print('  ' + ', '.join('0x%02x' % b for b in data[i:i + 24]) + ',')
print('};')
PY
  done
done
echo "#endif" >> "$TMP/h"
mv "$TMP/h" "$OUT"
echo "wrote $OUT"
